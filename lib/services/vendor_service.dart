class VendorService {
  static final VendorService _instance = VendorService._();
  static VendorService get instance => _instance;
  VendorService._();

  final Map<String, String> _cache = {};
  bool _initialized = false;

  Future<void> _init() async {
    if (_initialized) return;
    final prefs = await SharedPreferences.getInstance();
    final cachedData = prefs.getString('vendor_cache');
    if (cachedData != null) {
      try {
        final Map<String, dynamic> decoded = jsonDecode(cachedData);
        decoded.forEach((key, value) {
          _cache[key] = value.toString();
        });
      } catch (_) {}
    }
    _initialized = true;
  }

  Future<void> _saveCache() async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('vendor_cache', jsonEncode(_cache));
  }

  Future<String?> lookupVendor(String? macOrBssid) async {
    if (macOrBssid == null || macOrBssid.isEmpty) return null;
    
    final cleanMac = macOrBssid.toUpperCase().replaceAll(':', '').substring(0, 6);
    
    await _init();
    if (_cache.containsKey(cleanMac)) {
      return _cache[cleanMac];
    }

    try {
      // Using macvendors.com API - simple and no registration for low volume
      final response = await http
          .get(Uri.parse('https://api.macvendors.com/$cleanMac'))
          .timeout(const Duration(seconds: 2));
      
      if (response.statusCode == 200) {
        final vendor = response.body.trim();
        _cache[cleanMac] = vendor;
        await _saveCache();
        return vendor;
      }
    } catch (_) {
      // Silently fail and return null or a generic guess
    }

    // Basic hardcoded fallback for very common vendors if API fails
    return _guessVendor(cleanMac);
  }

  static String? inferVendorFromHost(String? host) {
    if (host == null || host.isEmpty) return null;
    final h = host.toLowerCase();

    // Infrastructure & Networking
    if (h.contains('gateway') || h.contains('router')) return 'Gateway/Router';
    if (h.contains('tplink') || h.contains('tp-link')) return 'TP-Link';
    if (h.contains('dlink') || h.contains('d-link')) return 'D-Link';
    if (h.contains('netgear')) return 'Netgear';
    if (h.contains('linksys')) return 'Linksys';
    if (h.contains('asus')) return 'ASUS';
    if (h.contains('ubnt') || h.contains('unifi')) return 'Ubiquiti';
    if (h.contains('cisco')) return 'Cisco';
    if (h.contains('mikrotik')) return 'MikroTik';
    if (h.contains('synology')) return 'Synology';
    if (h.contains('qnap')) return 'QNAP';

    // Major Tech Ecosystems
    if (h.contains('apple') || h.contains('iphone') || h.contains('ipad') || h.contains('macbook') || h.contains('mac-') || h.contains('airport')) return 'Apple';
    if (h.contains('samsung')) return 'Samsung';
    if (h.contains('google') || h.contains('android') || h.contains('chromecast') || h.contains('pixel-') || h.contains('nest')) return 'Google';
    if (h.contains('amazon') || h.contains('echo') || h.contains('kindle') || h.contains('firetv') || h.contains('alexa')) return 'Amazon';
    if (h.contains('microsoft') || h.contains('xbox') || h.contains('windows') || h.contains('surface-')) return 'Microsoft';

    // Mobile & Electronics
    if (h.contains('sony') || h.contains('playstation') || h.contains('bravia')) return 'Sony';
    if (h.contains('lg-') || h.contains('lge-') || h.contains('thinq')) return 'LG';
    if (h.contains('huawei')) return 'Huawei';
    if (h.contains('xiaomi')) return 'Xiaomi';
    if (h.contains('oneplus')) return 'OnePlus';
    if (h.contains('nvidia') || h.contains('shield')) return 'NVIDIA';

    // Printers
    if (h.contains('hp-') || h.contains('hp_') || h.contains('laserjet') || h.contains('deskjet') || h.contains('officejet')) return 'HP';
    if (h.contains('canon')) return 'Canon';
    if (h.contains('epson')) return 'Epson';
    if (h.contains('brother')) return 'Brother';

    // IoT & Audio
    if (h.contains('sonos')) return 'Sonos';
    if (h.contains('roku')) return 'Roku';
    if (h.contains('philips') || h.contains('hue')) return 'Philips';
    if (h.contains('bose')) return 'Bose';
    if (h.contains('denon')) return 'Denon';
    if (h.contains('marantz')) return 'Marantz';
    if (h.contains('yamaha')) return 'Yamaha';
    if (h.contains('bose')) return 'Bose';
    if (h.contains('raspberry')) return 'Raspberry Pi';
    if (h.contains('tesla')) return 'Tesla';

    return null;
  }

